#!/usr/bin/env python3
"""Regenerate listings-data.js (embedded fallback data) and supabase/seed.sql
from ~/workspace/malta-dashboard/listings.json.

Photos that tools/fetch-images.py has localized are referenced as
img/<sha1-12>.webp; any photo not downloaded yet keeps its remote URL."""
import hashlib
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC = os.path.expanduser("~/workspace/malta-dashboard/listings.json")
IMG_DIR = os.path.join(ROOT, "img")


def localize(url):
    name = hashlib.sha1(url.encode("utf-8")).hexdigest()[:12] + ".webp"
    if os.path.exists(os.path.join(IMG_DIR, name)):
        return "img/" + name
    return url


def main():
    with open(SRC) as f:
        data = json.load(f)
    data.sort(key=lambda x: x["rent"])
    for x in data:
        if x.get("images"):
            x["images"] = [localize(u) for u in x["images"]]

    js = "window.LISTINGS = " + json.dumps(data, ensure_ascii=False) + ";\n"
    with open(os.path.join(ROOT, "listings-data.js"), "w") as f:
        f.write(js)

    def esc(s):
        return s.replace("'", "''")

    lines = [
        "-- Seed for public.listings. Generated by tools/generate.py.",
        "-- Run in the Supabase SQL editor after schema.sql.",
        "insert into public.listings (url, rent, island, src, data) values",
    ]
    rows = []
    for x in data:
        payload = esc(json.dumps(x, ensure_ascii=False))
        rows.append(
            "  ('%s', %d, '%s', '%s', '%s'::jsonb)"
            % (esc(x["url"]), int(x["rent"]), esc(x["island"]), esc(x["src"]), payload)
        )
    lines.append(",\n".join(rows))
    lines.append("on conflict (url) do update set rent = excluded.rent, island = excluded.island, src = excluded.src, data = excluded.data;")
    with open(os.path.join(ROOT, "supabase", "seed.sql"), "w") as f:
        f.write("\n".join(lines) + "\n")

    print("listings:", len(data))


if __name__ == "__main__":
    main()
